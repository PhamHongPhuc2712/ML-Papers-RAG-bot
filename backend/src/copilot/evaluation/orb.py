"""Open RAG Bench (ORB), pinned, and its text slice frozen as an evaluation dataset.

ORB (Vectara, ``vectara/open_ragbench``) is 1,000 arXiv papers and 3,045
question-answer pairs, each labelled with one gold document and one gold section.
1,914 of the questions are answerable from text alone; the rest need a figure or a
table. This module fetches the benchmark at one commit, reads its four label files
and freezes the text slice in the retrieval harness's own dataset shape, with a
separate assignment of which questions the answering benchmark may score.

Two rules shape it. The dataset is CC-BY-NC-4.0: questions, answers, section text
and PDFs live under ``DATA_DIR`` and never reach the repository, a report or an
export; the repository copy carries ids, labels and the sample only. And the sample
is a function of the seed and the ids alone, sorted before shuffled, so a second
machine freezes the same 400 cases.
"""

from __future__ import annotations

import hashlib
import json
import random
import re
from collections import defaultdict
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from ..corpus.mirror import hf_fetch
from .datasets import (
    RETRIEVAL_SPLIT,
    Dataset,
    DatasetError,
    QrelRecord,
    QueryRecord,
    SplitRecord,
    read_dataset,
    write_dataset,
)

ORB_REPO = "vectara/open_ragbench"
# Verified 2026-10-06: 1,000 papers, 3,045 queries, 1,914 of them text-only.
ORB_REVISION = "63f6b052ff83508b08e242db42263ee708815c26"
ORB_LICENSE = "cc-by-nc-4.0"
ORB_AUTHOR = "Vectara, Open RAG Bench (questions generated by gpt-4o-mini)"
LABEL_MEMBERS = (
    "pdf/arxiv/queries.json",
    "pdf/arxiv/qrels.json",
    "pdf/arxiv/answers.json",
    "pdf/arxiv/pdf_urls.json",
)
CORPUS_PREFIX = "pdf/arxiv/corpus"
TEXT_SOURCE = "text"
QUERY_TYPES = ("abstractive", "extractive")
# Where a text query may be scored by the answering benchmark (O5): the frozen
# sample, scored once per configuration; the development cases, read while
# prompts settle; or neither, retrieval only.
QA_SPLITS = ("frozen", "development", "retrieval_only")
DEFAULT_SEED = 42
DEFAULT_FROZEN = 400
DEFAULT_DEVELOPMENT = 100
DEFAULT_PER_DOCUMENT = 2

_HEX40 = re.compile(r"^[0-9a-f]{40}$")


class OrbError(RuntimeError):
    """The benchmark cannot be fetched, read or sampled."""

    def __init__(self, code: str, detail: str = "") -> None:
        self.code = code
        super().__init__(f"{code}:{detail}" if detail else code)


class UnpinnedRevisionError(OrbError):
    """A benchmark fetched from a moving ref is not a reproducible benchmark."""

    def __init__(self, revision: str) -> None:
        super().__init__("unpinned_revision", revision or "<empty>")


@dataclass(frozen=True, slots=True)
class OrbPaths:
    """Where the benchmark lives under ``DATA_DIR/benchmarks/orb``."""

    root: Path

    @property
    def labels(self) -> Path:
        return self.root / "pdf" / "arxiv"

    @property
    def corpus(self) -> Path:
        return self.labels / "corpus"

    @property
    def pdfs(self) -> Path:
        return self.root / "pdfs"

    @property
    def dataset(self) -> Path:
        """The hydratable copy: the repository's files plus the text they omit."""

        return self.root / "dataset"

    def member(self, name: str) -> Path:
        return self.root / name

    def corpus_file(self, doc_id: str) -> Path:
        return self.corpus / f"{doc_id}.json"


@dataclass(frozen=True, slots=True)
class OrbQuery:
    query_id: str
    query: str
    type: str
    source: str
    doc_id: str
    section_id: int
    answer: str


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fetch_orb(paths: OrbPaths, *, revision: str = ORB_REVISION) -> dict[str, Any]:
    """Download the label files and the 1,000 corpus files at a pinned commit.

    Refuses a moving ref. Returns the sha256 of each label file and one digest
    over the corpus files, which is what ``configs/evaluation.yaml`` records.
    """

    if not _HEX40.match(revision or ""):
        raise UnpinnedRevisionError(revision)
    paths.root.mkdir(parents=True, exist_ok=True)
    checksums: dict[str, Any] = {}
    for member in LABEL_MEMBERS:
        checksums[member] = _sha256(hf_fetch(ORB_REPO, revision, member, paths.root))
    urls = json.loads(paths.member("pdf/arxiv/pdf_urls.json").read_text(encoding="utf-8"))
    if not isinstance(urls, Mapping) or not urls:
        raise OrbError("pdf_urls_invalid")
    lines = []
    for doc_id in sorted(urls):
        member = f"{CORPUS_PREFIX}/{doc_id}.json"
        lines.append(f"{member}:{_sha256(hf_fetch(ORB_REPO, revision, member, paths.root))}")
    checksums["corpus"] = {
        "files": len(lines),
        "sha256": hashlib.sha256("\n".join(lines).encode()).hexdigest(),
    }
    return checksums


def _read_json(path: Path) -> dict[str, Any]:
    if not path.exists():
        raise OrbError("missing_file", str(path))
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise OrbError("label_file_invalid", str(path))
    return data


def load_orb(paths: OrbPaths) -> list[OrbQuery]:
    """The 3,045 queries joined to their labels and reference answers, in id order."""

    queries = _read_json(paths.member("pdf/arxiv/queries.json"))
    qrels = _read_json(paths.member("pdf/arxiv/qrels.json"))
    answers = _read_json(paths.member("pdf/arxiv/answers.json"))
    urls = _read_json(paths.member("pdf/arxiv/pdf_urls.json"))
    out: list[OrbQuery] = []
    for query_id in sorted(queries):
        row = queries[query_id]
        label = qrels.get(query_id)
        if not isinstance(row, Mapping) or not isinstance(label, Mapping):
            raise OrbError("query_without_label", query_id)
        doc_id = str(label["doc_id"])
        if doc_id not in urls:
            raise OrbError("gold_without_pdf", doc_id)
        if str(row["type"]) not in QUERY_TYPES:
            raise OrbError("unknown_query_type", str(row["type"]))
        out.append(
            OrbQuery(
                query_id=query_id,
                query=str(row["query"]),
                type=str(row["type"]),
                source=str(row["source"]),
                doc_id=doc_id,
                section_id=int(label["section_id"]),
                answer=str(answers.get(query_id, "")),
            )
        )
    return out


def text_slice(queries: Iterable[OrbQuery]) -> list[OrbQuery]:
    """The queries answerable from text alone, the ones this pipeline can serve."""

    return [query for query in queries if query.source == TEXT_SOURCE]


def sample_qa(
    queries: Sequence[OrbQuery],
    *,
    seed: int = DEFAULT_SEED,
    frozen: int = DEFAULT_FROZEN,
    development: int = DEFAULT_DEVELOPMENT,
    per_document: int = DEFAULT_PER_DOCUMENT,
) -> dict[str, str]:
    """Which queries the answering benchmark may score, and in which role.

    Stratified by ``type``: each stratum's ids are sorted, then shuffled by a seed
    of their own, and the strata are walked round-robin so the frozen sample
    holds the types in equal numbers. A query is taken only while its gold
    document is under ``per_document`` across both sets, because questions from
    one paper succeed or fail together. ``frozen`` fills first, then
    ``development``; everything else is ``retrieval_only``.
    """

    if frozen < 0 or development < 0 or per_document < 1:
        raise OrbError("sample_invalid")
    strata: defaultdict[str, list[str]] = defaultdict(list)
    documents: dict[str, str] = {}
    for query in queries:
        strata[query.type].append(query.query_id)
        documents[query.query_id] = query.doc_id
    order = sorted(strata)
    queues: dict[str, list[str]] = {}
    for kind in order:
        ids = sorted(strata[kind])
        random.Random(f"{seed}:{kind}").shuffle(ids)
        queues[kind] = ids

    assignment = {query_id: "retrieval_only" for query_id in documents}
    taken: defaultdict[str, int] = defaultdict(int)
    positions = dict.fromkeys(order, 0)

    def take(kind: str) -> str | None:
        queue = queues[kind]
        while positions[kind] < len(queue):
            query_id = queue[positions[kind]]
            positions[kind] += 1
            if taken[documents[query_id]] < per_document:
                taken[documents[query_id]] += 1
                return query_id
        return None

    for role, wanted in (("frozen", frozen), ("development", development)):
        filled = 0
        exhausted: set[str] = set()
        while filled < wanted and len(exhausted) < len(order):
            for kind in order:
                if filled >= wanted or kind in exhausted:
                    continue
                query_id = take(kind)
                if query_id is None:
                    exhausted.add(kind)
                    continue
                assignment[query_id] = role
                filled += 1
    return assignment


def _query_set(kind: str) -> str:
    return f"orb_{kind}"


def _dump(path: Path, rows: Iterable[Mapping[str, Any]]) -> None:
    with path.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(dict(row), sort_keys=True) + "\n")


def _load(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        raise DatasetError("missing_file", str(path))
    return [
        json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()
    ]


def write_orb_dataset(
    queries: Sequence[OrbQuery],
    assignment: Mapping[str, str],
    directory: Path,
    *,
    include_text: bool,
    paper_ids: Mapping[str, str] | None = None,
    revision: str = ORB_REVISION,
) -> None:
    """Write the slice in the harness's shape, plus ORB's own files beside it.

    ``queries.jsonl``, ``qrels.jsonl`` and ``splits.jsonl`` are what
    ``eval retrieval`` reads: every query in the single ``retrieval`` split, a
    family per gold document, one qrel per query naming the gold document and,
    once the corpus is loaded, its paper id. ``sections.jsonl`` keeps the gold
    section and ``qa.jsonl`` the answering assignment. With ``include_text`` the
    copy also carries the question text and ``answers.jsonl``; without it,
    nothing licensed leaves ``DATA_DIR``.
    """

    for query in queries:
        if assignment.get(query.query_id) not in QA_SPLITS:
            raise OrbError("query_unassigned", query.query_id)
    ids = paper_ids or {}
    dataset = Dataset(
        queries=tuple(
            QueryRecord(
                query_id=query.query_id,
                query=query.query,
                query_set=_query_set(query.type),
                workflow="grounded_qa",
                # One gold document per query: every ORB question is specific.
                specificity=1,
                quality=2,
                # The gold document is in the benchmark's own corpus by construction.
                in_domain=True,
                source=f"orb@{revision}",
                author=ORB_AUTHOR,
            )
            for query in queries
        ),
        qrels=tuple(
            QrelRecord(
                query_id=query.query_id,
                corpusid=query.doc_id,
                grade=1,
                paper_id=ids.get(query.doc_id),
            )
            for query in queries
        ),
        splits=tuple(
            SplitRecord(query_id=query.query_id, family_id=query.doc_id, split=RETRIEVAL_SPLIT)
            for query in queries
        ),
    )
    write_dataset(dataset, directory, include_query_text=include_text)
    _dump(
        directory / "sections.jsonl",
        ({"query_id": q.query_id, "doc_id": q.doc_id, "section_id": q.section_id} for q in queries),
    )
    _dump(
        directory / "qa.jsonl",
        ({"query_id": q.query_id, "qa_split": assignment[q.query_id]} for q in queries),
    )
    if include_text:
        _dump(
            directory / "answers.jsonl",
            ({"query_id": q.query_id, "answer": q.answer} for q in queries),
        )


def read_qa_assignment(directory: Path) -> dict[str, str]:
    """Query id to ``frozen`` / ``development`` / ``retrieval_only``."""

    assignment = {
        str(row["query_id"]): str(row["qa_split"]) for row in _load(directory / "qa.jsonl")
    }
    if any(value not in QA_SPLITS for value in assignment.values()):
        raise OrbError("qa_split_invalid")
    return assignment


def read_sections(directory: Path) -> dict[str, tuple[str, int]]:
    """Query id to (gold document, gold section)."""

    return {
        str(row["query_id"]): (str(row["doc_id"]), int(row["section_id"]))
        for row in _load(directory / "sections.jsonl")
    }


def hydrate_orb(dataset: Dataset, paths: OrbPaths) -> Dataset:
    """Re-attach the question text from the copy under ``DATA_DIR``."""

    from .datasets import hydrate

    texts = {
        str(row["query_id"]): str(row.get("query", ""))
        for row in _load(paths.dataset / "queries.jsonl")
    }
    return hydrate(dataset, texts)


def paper_ids_for(doc_ids: Iterable[str], engine: Any) -> dict[str, str]:
    """Gold arXiv ids to the paper ids the loaded corpus gave them.

    The identity layer stores an arXiv id without its version and keeps the
    version beside it, so a versioned ORB id is looked up by its stem. A gold
    document with no paper is left out, never guessed from a title.
    """

    from sqlalchemy import select

    from ..corpus.normalize import normalize_arxiv
    from ..db.models import PaperIdentifier
    from ..db.session import session_scope

    stems: dict[str, list[str]] = defaultdict(list)
    for doc_id in doc_ids:
        stem, _ = normalize_arxiv(doc_id)
        stems[stem].append(doc_id)
    found: dict[str, str] = {}
    with session_scope(engine) as session:
        rows = session.execute(
            select(PaperIdentifier.value, PaperIdentifier.paper_id).where(
                PaperIdentifier.namespace == "arxiv", PaperIdentifier.value.in_(list(stems))
            )
        ).all()
    for value, paper_id in rows:
        for doc_id in stems.get(str(value), []):
            found[doc_id] = str(paper_id)
    return found


def dataset_counts(directory: Path) -> dict[str, Any]:
    """What a written dataset holds, for the record."""

    dataset = read_dataset(directory)
    assignment = read_qa_assignment(directory)
    by_type: defaultdict[str, defaultdict[str, int]] = defaultdict(lambda: defaultdict(int))
    for query in dataset.queries:
        by_type[query.query_set][assignment[query.query_id]] += 1
    return {
        "queries": len(dataset.queries),
        "documents": len({record.corpusid for record in dataset.qrels}),
        "with_paper_id": sum(1 for record in dataset.qrels if record.paper_id),
        "qa": {kind: dict(sorted(counts.items())) for kind, counts in sorted(by_type.items())},
    }
